/* SOUNDTST.PRO: the debug sound test ("サウンドテスト"). The tester picks a sound bank (VAB) from
 * soundtst_banks, the overlay loads it, then plays the bank's sounds (soundtst_bank_sounds). The buttons are
 * read as raw bits, not through the button map. */

void soundtst_update_root();
void soundtst_update();

/* An entry of the bank and sound lists, ended by id 0. */
typedef struct SoundTestEntry {
    /* 0x0 */ u8 *name;
    /* 0x4 */ s32 id;
} SoundTestEntry; /* size 0x8 */

/* Object of soundtst_update. */
typedef struct SoundTest {
    /* 0x00 */ Object base;
    /* 0x50 */ s32 bank_cursor; /* bank under the cursor */
    /* 0x54 */ s32 first_bank; /* first bank shown */
    /* 0x58 */ s32 bank_count; /* number of banks */
    /* 0x5C */ s32 bank_to_load; /* bank to load */
    /* 0x60 */ s32 sound_cursor; /* sound under the cursor */
    /* 0x64 */ s32 first_sound; /* first sound shown */
    /* 0x68 */ s32 sound_count; /* number of sounds in the bank */
    /* 0x6C */ s32 playing; /* a sound is playing (key on) */
    /* 0x70 */ s32 voice;  /* its voice */
} SoundTest; /* size 0x74 */

/* Data of soundtst_update: its windows. */
typedef struct SoundTestData {
    /* 0x00 */ MessageWindow *title;  /* title */
    /* 0x04 */ MessageWindow *heading; /* heading: the bank */
    /* 0x08 */ MessageWindow *cursor; /* cursor */
    /* 0x0C */ MessageWindow *list[8];   /* the list */
} SoundTestData; /* size 0x2C */

