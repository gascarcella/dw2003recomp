Object *soundtst_create(void);

void soundtst_update_root(Object *obj, Object **data) {
    switch (obj->state) {
    case OBJECT_STATE_INIT:
    default:
        *data = soundtst_create();
        obj->next_state(obj);
        break;
    case OBJECT_STATE_RUN:
        if (pad_state.get_pressed(0) & 8) {
            gamestate_data.funcs.set_next_map(0x1500, 0);
            obj->next_state(obj);
        }
        break;
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

Object *soundtst_start(void) {
    return object_new(soundtst_update_root, sizeof(Object), 4);
}

/* Moves the cursor of a list of `count` entries by `dir`, scrolling so that 8 entries are shown. */
void soundtst_move_cursor(SoundTest *obj, s32 dir, s32 *cursor, s32 *top, s32 count) {
    s32 n = *cursor + dir;

    if (n >= 0 && n < count) {
        *cursor = n;
        if (n >= *top + 8) {
            *top = n - 7;
        }
        if (*top > *cursor) {
            *top = *cursor;
        }
    }
}

/* Plays the sounds of the bank. */
void soundtst_play_sounds(SoundTest *obj, SoundTestData *data) {
    SoundTestEntry *sounds = soundtst_bank_sounds[obj->bank_cursor];
    s32 i;
    s32 top;

    switch (obj->base.substep) {
    case 0:
    default:
        obj->sound_cursor = 0;
        obj->first_sound = 0;
        obj->sound_count = 0;
        while (sounds[obj->sound_count].id != 0) {
            obj->sound_count++;
        }
        data->heading->copy_text(data->heading, soundtst_banks[obj->bank_cursor].name);
        obj->playing = 0;
        obj->base.next_substep(obj);
        break;
    case 1:
        break;
    }
    if ((pad_state.get_pressed(0) | pad_state.get_repeat(0)) & 0x40) {
        soundtst_move_cursor(obj, 1, &obj->sound_cursor, &obj->first_sound, obj->sound_count);
    } else if ((pad_state.get_pressed(0) | pad_state.get_repeat(0)) & 0x10) {
        soundtst_move_cursor(obj, -1, &obj->sound_cursor, &obj->first_sound, obj->sound_count);
    } else if (pad_state.get_pressed(0) & 0x8000) {
        sound_module.stop_all();
    } else if (pad_state.get_pressed(0) & 0x4000) {
        obj->base.set_step(obj, 0);
    } else if (pad_state.get_pressed(0) & 0x2000) {
        obj->voice = (s16)sound_module.play(sounds[obj->sound_cursor].id); /* the voice is an s16 (sound_key_off) */
        obj->playing = 1;
    } else if (obj->playing != 0 && !(pad_state.get_held(0) & 0x2000)) {
        obj->playing = 0;
        sound_module.key_off(sounds[obj->sound_cursor].id, obj->voice);
    }
    for (i = 0, top = obj->first_sound; i < 8 && sounds[top].id != 0; i++, top++) {
        data->list[i]->copy_text(data->list[i], sounds[top].name);
        data->list[i]->set_visible(data->list[i], 1);
    }
    for (; i < 8; i++) {
        data->list[i]->set_visible(data->list[i], 0);
    }
    data->cursor->set_pos(data->cursor, 0x20, (obj->sound_cursor - obj->first_sound) * 16 + 0x46);
}

/* Loads the chosen bank (unk_5C; bank 1 through sound_load_bank). */
void soundtst_load_bank(SoundTest *obj, SoundTestData *data) {
    switch (obj->base.substep) {
    case 0:
    default:
        if (obj->bank_to_load == 1) {
            sound_module.load_bank(0, 1);
        } else {
            sound_module.load_extra_bank(obj->bank_to_load);
        }
        obj->base.substep++;
        break;
    case 1:
        break;
    }
    if (sound_module.is_loading() == 0) {
        obj->base.next_step(obj);
    }
}

/* Chooses the bank. */
void soundtst_choose_bank(SoundTest *obj, SoundTestData *data) {
    s32 i;
    s32 top;

    switch (obj->base.substep) {
    case 0:
    default:
        obj->bank_count = 0;
        while (soundtst_banks[obj->bank_count].id != 0) {
            obj->bank_count++;
        }
        /* "−てんそうするＶＡＢをせんたくしてください−" (choose the VAB to transfer) */
        data->heading->copy_text(data->heading, "\x81\x7C\x82\xC4\x82\xF1\x82\xBB\x82\xA4\x82\xB7\x82\xE9\x82\x75\x82\x60"
                                            "\x82\x61\x82\xF0\x82\xB9\x82\xF1\x82\xBD\x82\xAD\x82\xB5\x82\xC4\x82\xAD"
                                            "\x82\xBE\x82\xB3\x82\xA2\x81\x7C");
        obj->base.next_substep(obj);
        break;
    case 1:
        break;
    }
    if ((pad_state.get_pressed(0) | pad_state.get_repeat(0)) & 0x40) {
        soundtst_move_cursor(obj, 1, &obj->bank_cursor, &obj->first_bank, obj->bank_count);
    } else if ((pad_state.get_pressed(0) | pad_state.get_repeat(0)) & 0x10) {
        soundtst_move_cursor(obj, -1, &obj->bank_cursor, &obj->first_bank, obj->bank_count);
    } else if (pad_state.get_pressed(0) & 0x2000) {
        obj->bank_to_load = soundtst_banks[obj->bank_cursor].id;
        obj->base.next_step(obj);
    }
    for (i = 0, top = obj->first_bank; i < 8 && soundtst_banks[top].id != 0; i++, top++) {
        data->list[i]->copy_text(data->list[i], soundtst_banks[top].name);
        data->list[i]->set_visible(data->list[i], 1);
    }
    for (; i < 8; i++) {
        data->list[i]->set_visible(data->list[i], 0);
    }
    data->cursor->set_pos(data->cursor, 0x20, (obj->bank_cursor - obj->first_bank) * 16 + 0x46);
}

void soundtst_update(SoundTest *obj, SoundTestData *data) {
    GfxLayer *layer;
    s32 i;

    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        gfx_module.reset();
        gfx_module.alloc_packet_buffers(0x5000);
        gfx_module.funcs.init_display(0x140, 0xF0, 0, 0);
        layer = gfx_module.funcs.create_layer(&soundtst_screen_rect, 1, 0x1000);
        layer->set_bg_color(layer, 0x1F, 0x1F, 0x1F);
        data->title = message_create_window(0x1000, 1, 0x10, 0x1E);
        /* "サウンドテスト" (sound test) */
        data->title->copy_text(data->title, "\x83\x54\x83\x45\x83\x93\x83\x68\x83\x65\x83\x58\x83\x67");
        data->heading = message_create_window(0x1000, 1, 0x20, 0x32);
        for (i = 0; i < 8; i++) {
            data->list[i] = message_create_window(0x1000, 1, 0x30, i * 16 + 0x46);
        }
        data->cursor = message_create_window(0x1000, 1, 0x20, 0x46);
        data->cursor->copy_text(data->cursor, soundtst_cursor_text);
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
        switch (obj->base.step) {
        case 0:
        default:
            soundtst_choose_bank(obj, data);
            break;
        case 1:
            soundtst_load_bank(obj, data);
            break;
        case 2:
            soundtst_play_sounds(obj, data);
            break;
        }
        break;
    case OBJECT_STATE_DONE:
        break;
    case OBJECT_STATE_END:
        gamestate_data.funcs.set_next_map(0x1500, 0);
        break;
    }
}

