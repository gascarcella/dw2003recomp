/* The stage module (stgmcard_module): the screen's pictures and text, the save file's header and buffers,
 * fades and moving values. FIELDSTG and STDWTITL end with the same module (the last four functions are the
 * same code). */

/* The save file's icon: its palette, then its three frames. */
extern void *stgmcard_icon[4];

/* Loads the screen's pictures, sets the save file's header (title from the text file, icon), allocates the
 * buffers and starts loading the text files. */
void stgmcard_init_save_header(void) {
    Tim tim;
    Font font;
    char title[0x41];
    void *icons[3];
    void *clut;

    tim_init(&tim);
    tim.set_image_pos(0x280, 0);
    tim.load_all(cdload_module.get_subfile_by_id(0x029E0000));
    heap_funcs.bzero(title, sizeof(title));
    font_init(&font);
    font.convert_text(title, font.get_entry(cdload_module.files.get_file(records_language + 0x78), 0x27), 0);
    clut = stgmcard_icon[0];
    icons[0] = stgmcard_icon[1];
    icons[1] = stgmcard_icon[2];
    icons[2] = stgmcard_icon[3];
    memcard_funcs.set_header(title, clut, 3, icons);
    if (stgmcard_module.save != NULL) {
        heap_funcs.free(stgmcard_module.save);
    }
    stgmcard_module.save_size = 0x2780;
    stgmcard_module.save = heap_funcs.alloc(0x2780, 2);
    if (stgmcard_module.header != NULL) {
        heap_funcs.free(stgmcard_module.header);
    }
    stgmcard_module.header_size = 0x180;
    stgmcard_module.header = heap_funcs.alloc(0x180, 2);
    cdload_module.queue_file(records_language + 0x78);
    cdload_module.queue_file(records_language + 0xA9);
    cdload_module.queue_file(records_language + 0x94);
}

/* Returns non-zero while a text file is still loading. */
s32 stgmcard_is_loading(void) {
    if (cdload_module.is_loading(records_language + 0x78) != 0) {
        return 1;
    }
    if (cdload_module.is_loading(records_language + 0xA9) != 0) {
        return 1;
    }
    return cdload_module.is_loading(records_language + 0x94) != 0;
}

/* Frees the buffers. */
void stgmcard_free_buffers(void) {
    if (stgmcard_module.save != NULL) {
        heap_funcs.free(stgmcard_module.save);
    }
    if (stgmcard_module.header != NULL) {
        heap_funcs.free(stgmcard_module.header);
    }
}

/* Starts opening (`open`) or closing; plays the matching sound (window_anim_start). */
void stgmcard_start_fade(WindowAnim *anim, s32 open) {
    anim->running = 1;
    if (open) {
        sound_module.play(0x40019);
        anim->step = 0x1000 / anim->duration;
        anim->level = 0;
    } else {
        sound_module.play(0x4001A);
        anim->level = 0x1000;
        anim->step = -(0x1000 / anim->duration * 2);
    }
}

/* Steps the fade; returns 1 once it is finished (or not running) (window_anim_update). */
s32 stgmcard_update_fade(WindowAnim *anim) {
    if (anim->running == 0) {
        return 1;
    }
    anim->level += anim->step;
    if (anim->step > 0) {
        if (anim->level > 0x1000) {
            anim->level = 0x1000;
            anim->running = 0;
            return 1;
        }
    } else if (anim->level < 0) {
        anim->level = 0;
        anim->running = 0;
        return 1;
    }
    return 0;
}

/* Starts moving `v` from `from` to `to` in `frames` frames. */
void stgmcard_start_value(Tween *v, s32 from, s32 to, s32 frames) {
    if (from != to) {
        v->duration = frames;
        v->acc = from << 8;
        v->value = from;
        v->target = to;
        v->running = 1;
        v->step = ((to - from) << 8) / v->duration;
    }
}

/* Steps `v`; returns 1 once it reached its target (or isn't moving). */
s32 stgmcard_step_value(Tween *v) {
    if (v->running == 0) {
        return 1;
    }
    v->acc += v->step;
    v->value = v->acc >> 8;
    if (v->step > 0) {
        if (v->value > v->target) {
            v->value = v->target;
            v->running = 0;
            return 1;
        }
    } else {
        if (v->value < v->target) {
            v->value = v->target;
            v->running = 0;
            return 1;
        }
    }
    return 0;
}

StgmcardModule stgmcard_module = {
    .init_save_header = stgmcard_init_save_header,
    .is_loading = stgmcard_is_loading,
    .free_buffers = stgmcard_free_buffers,
    .start_fade = stgmcard_start_fade,
    .update_fade = stgmcard_update_fade,
    .start_value = stgmcard_start_value,
    .step_value = stgmcard_step_value,
};

