/* A list menu (data block: its 14 windows): up/down move the cursor (10 at a time while 0x8000 is held), 0x2000
 * picks, 0x4000 cancels; the cursor's window blinks. */
void wfightts_stage_menu_update(WfighttsStageMenu *obj, MessageWindow **windows) {
    s32 i;
    s32 j;
    s32 k;
    s32 pressed;
    s32 step;

    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        for (i = 0; i < 14; i++) {
            windows[i] = message_create_window(0x1005, 1, 180, 40 + i * 12);
        }
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
        pressed = pad_state.get_pressed(0) | pad_state.get_repeat(0);
        if (pad_state.get_held(0) & 0x8000) {
            step = 10;
        } else {
            step = 1;
        }
        if (pressed & 0x10) {
            for (j = 0; j < step; j++) {
                if (wfightts_stage_menu_cursor != 0) {
                    wfightts_stage_menu_cursor--;
                } else if (wfightts_stage_menu_first_line != 0) {
                    wfightts_stage_menu_first_line--;
                }
            }
        } else if (pressed & 0x40) {
            for (j = 0; j < step; j++) {
                if (wfightts_stage_menu_cursor != 13) {
                    wfightts_stage_menu_cursor++;
                } else if (wfightts_stage_menu_first_line != 41) {
                    wfightts_stage_menu_first_line++;
                }
            }
        } else {
            if (pressed & 0x2000) {
                *obj->result = wfightts_stage_menu_first_line + wfightts_stage_menu_cursor + 1;
                obj->base.set_state(obj, OBJECT_STATE_END);
            }
            if (pressed & 0x4000) {
                *obj->result = -1;
                obj->base.set_state(obj, OBJECT_STATE_END);
            }
        }
        for (k = 0; k < 14; k++) {
            if (wfightts_stage_menu_cursor == k && (gfx_module.funcs.get_time() & 8)) {
                windows[k]->set_visible(windows[k], 0);
            } else {
                windows[k]->set_visible(windows[k], 1);
                windows[k]->copy_text(windows[k], wfightts_stage_names[k + wfightts_stage_menu_first_line]);
            }
        }
        break;
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WfighttsStageMenu *wfightts_stage_menu_create(s32 *arg0) {
    WfighttsStageMenu *obj = object_new(wfightts_stage_menu_update, sizeof(WfighttsStageMenu), 0x38);

    obj->result = arg0;
    return obj;
}
