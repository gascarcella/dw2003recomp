/* STAGSLCT.PRO: the debug stage select ("ステージセレクト"). A list of stages (stagslct_stages) to jump to,
 * the language (START cycles records_language), the BIOS version, and cheats on the second controller: the party's level
 * and one stat, and two values of records_state. */

void stagslct_update_root();
void stagslct_update();

/* `button` (through the button map) is held on port `port`. */
#define PAD_HELD_PORT(port, button) ((pad_state.get_held(port) >> pad_state.get_button_map(port, button)) & 1)
#define PAD_PRESSED_PORT(port, button) ((pad_state.get_pressed(port) >> pad_state.get_button_map(port, button)) & 1)
#define PAD_REPEAT_PORT(port, button) ((pad_state.get_repeat(port) >> pad_state.get_button_map(port, button)) & 1)

/* A stage of the list, ended by stage -1; stage 0 is a separator, 0x300 sets gamestate_data.progress instead. */
typedef struct StageSelectEntry {
    /* 0x0 */ u8 *name;
    /* 0x4 */ u8 *label;
    /* 0x8 */ s32 stage; /* for gamestate_data.funcs.set_next_map */
    /* 0xC */ s32 arg;   /* its argument; bit 15: goes to gamestate_data.progress instead */
} StageSelectEntry; /* size 0x10 */

/* Object of stagslct_update. */
typedef struct StageSelect {
    /* 0x00 */ Object base;
    /* 0x50 */ s32 cursor_row; /* cursor row */
    /* 0x54 */ s32 first_stage; /* first stage shown */
    /* 0x58 */ s32 rows_shown; /* rows shown (up to 14) */
    /* 0x5C */ s32 stage_count; /* number of stages */
    /* 0x60 */ s32 version_made; /* the version text is made */
    /* 0x64 */ s32 fading; /* fading (stagslct_fade_title) */
    /* 0x68 */ s32 fade_level; /* fade level, 0..0x1000 */
    /* 0x6C */ s32 fade_step; /* fade step */
} StageSelect; /* size 0x70 */

/* Data of stagslct_update: its windows. */
typedef struct StageSelectData {
    /* 0x00 */ MessageWindow *title;      /* title */
    /* 0x04 */ MessageWindow *cursor;     /* cursor */
    /* 0x08 */ MessageWindow *names[14];  /* names */
    /* 0x40 */ MessageWindow *labels[14]; /* labels */
    /* 0x78 */ MessageWindow *bios_version; /* BIOS version */
    /* 0x7C */ u8 unk_7C[0x4];
    /* 0x80 */ MessageWindow *language;   /* language */
    /* 0x84 */ MessageWindow *progress;   /* gamestate_data.progress */
    /* 0x88 */ MessageWindow *encounters; /* records_state.encounters */
    /* 0x8C */ MessageWindow *stat_11;     /* stat 11 of the first party member */
    /* 0x90 */ MessageWindow *level;     /* level of the first party member */
    /* 0x94 */ MessageWindow *unk_94;     /* records_state.cursor */
    /* 0x98 */ MessageWindow *unk_98;     /* records_state.names */
} StageSelectData; /* size 0x9C */

