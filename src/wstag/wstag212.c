s32 wstag212_sprite_anim_play_once(WstagSpriteAnim *sa, WstagAnimKey *keys, s32 depth) {
    WstagAnimKey *key = &keys[sa->anim.key];
    s32 step = gfx_module.funcs.get_frame_ticks();

    if (step >= 5) {
        step = 4;
    }
    if (depth == 0) {
        sa->anim.time -= step;
    }
    if (sa->anim.time <= 0) {
        key++;
        sa->anim.key++;
        sa->anim.time += key->time;
        if (key->frame == 0xFF) {
            return 0xFF;
        }
        wstag212_sprite_anim_play_once(sa, keys, depth + 1);
    }
    return key->frame;
}

void wstag212_sprite_anim_reset(WstagSpriteAnimObject *obj) {
    s32 i;

    for (i = 0; i < 3; i++) {
        obj->sprites[i].anim.key = 0;
        obj->sprites[i].anim.time = D_WSTAG212_800A816C[i]->time;
    }
}

void wstag212_sprite_anim_update(WstagSpriteAnimObject *obj) {
    FieldstgSprite *list;
    FieldstgSprite *sprite;
    s32 n;
    s32 i;
    s32 j;
    s32 done;
    s32 frame;

    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        wstag212_sprite_anim_reset(obj);
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
        switch (obj->base.step) {
        case 0:
            break;
        case 1:
            switch (obj->base.substep) {
            case 0:
                list = fieldstg_stage.sprites;
                for (n = 0; list->present != 0; list++) {
                    if (list->type >= 1 && list->type <= 3) {
                        obj->sprites[n].sprite = list;
                        list->x = obj->x;
                        list->y = obj->y;
                        list->priority = obj->y + D_WSTAG212_800A8178[n];
                        n++;
                    }
                }
                obj->base.next_substep(obj);
            case 1:
                done = 0;
                for (i = 0; i < 3; i++) {
                    sprite = obj->sprites[i].sprite;
                    frame = wstag212_sprite_anim_play_once(&obj->sprites[i], D_WSTAG212_800A816C[i], 0);
                    switch (frame) {
                    case 0xFF:
                        done++;
                        sprite->shown = 0;
                        sprite->sprite = 0;
                        break;
                    case 0x12C:
                        sprite->shown = 0;
                        sprite->sprite = 0;
                        break;
                    default:
                        sprite->shown = 1;
                        sprite->sprite = frame;
                        break;
                    }
                }
                if (done < 3) {
                    break;
                }
                obj->base.next_substep(obj);
            case 2:
                for (j = 0; j < 3; j++) {
                    obj->sprites[j].sprite->shown = 0;
                }
                wstag212_sprite_anim_reset(obj);
                obj->base.set_step(obj, 0);
                break;
            }
            break;
        }
        break;
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

void wstag212_sprite_anim_message(WstagSpriteAnimObject *obj, s32 msg) {
    s32 i;

    if (obj == NULL) {
        return;
    }
    i = 0;
    switch (msg) {
    case 0x33B:
        i++;
    case 0x33A:
        i++;
    case 0x32F:
        obj->x = D_WSTAG212_800A817C[i].x;
        obj->y = D_WSTAG212_800A817C[i].y;
        obj->base.set_step(obj, 1);
        sound_module.play(D_WSTAG212_800A8188[i]);
        break;
    }
}

WstagSpriteAnimObject *wstag212_sprite_anim_create(s32 arg0) {
    return object_create(wstag212_sprite_anim_update, sizeof(WstagSpriteAnimObject), 0, arg0);
}

void wstag212_update(WstagObject *obj, WstagEventData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        if (gamestate_data.progress == 2 && gamestate_flags.get_flag(0x7000, 1)) {
            data->event = fieldstg_event_start(0xA);
        } else if (gamestate_data.progress == 2 && gamestate_flags.get_flag(0x7001, 1)) {
            data->event = fieldstg_event_start(0xB);
        } else if (gamestate_data.progress == 2 && gamestate_flags.get_flag(0x7002, 1)) {
            data->event = fieldstg_event_start(0xC);
        } else if (gamestate_data.progress == 0xB && gamestate_flags.get_flag(0x4004, 0)) {
            data->event = fieldstg_event_start(0x10F);
        } else if (gamestate_data.progress == 0xB && gamestate_flags.get_flag(0x4004, 1)) {
            data->event = fieldstg_event_start(0x111);
        } else if (gamestate_data.progress == 0xD && gamestate_flags.get_flag(0x1C0D, 1)) {
            data->event = fieldstg_event_start(0x160);
        }
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag212_start(void *arg0) {
    WstagObject *obj = object_new(wstag212_update, sizeof(WstagObject), sizeof(FieldstgEvent *));

    obj->manager = arg0;
    wstag212_funcs.setup();
    return obj;
}

