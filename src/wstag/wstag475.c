void wstag475_update(WstagObject *obj, WstagEventData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        if (gamestate_data.progress == 8 && gamestate_flags.get_flag(0x1A17, 0) && gamestate_flags.get_flag(0x1C43, 1)) {
            data->event = fieldstg_event_start(0xB4);
        } else if (gamestate_data.progress == 8 && gamestate_flags.get_flag(0x1C43, 0)) {
            data->event = fieldstg_event_start(0xB5);
        } else if (gamestate_flags.get_flag(0x1A17, 1) && gamestate_flags.get_flag(0x1A19, 0)) {
            data->event = fieldstg_event_start(0xBE);
        } else if (gamestate_flags.get_flag(0x1A17, 1) && gamestate_flags.get_flag(0x1A19, 1) && gamestate_flags.get_flag(0x8015, 0)) {
            data->event = fieldstg_event_start(0xC8);
        } else if (gamestate_data.progress == 9 && gamestate_flags.get_flag(0x8015, 1)) {
            data->event = fieldstg_event_start(0xE6);
        }
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag475_start(void *arg0) {
    WstagObject *obj = object_new(wstag475_update, sizeof(WstagObject), sizeof(FieldstgEvent *));

    obj->manager = arg0;
    wstag475_funcs.setup();
    return obj;
}

