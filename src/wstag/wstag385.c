    fieldstg_stage.background_file = 0x513;
    fieldstg_stage.sprite_file = 0x04F80000;
    fieldstg_stage.sprites = wstag385_sprites;
    fieldstg_stage.map_events = wstag385_map_events;
    fieldstg_stage.mask_file = 0x4F7;
