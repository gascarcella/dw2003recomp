    fieldstg_stage.actors = wstag385_actors;
    fieldstg_stage.color = wstag385_color;
    fieldstg_stage.events = wstag385_events;
    fieldstg_stage.battle_lists = &wstag385_battle_lists;
    fieldstg_attr.set_file(0, 0x04F80001);
