void wstag385_update(WstagObject *obj, WstagEventData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        obj->base.next_state(obj);
        if (gamestate_flags.get_flag(0x402D, 1) && gamestate_flags.get_flag(0x402E, 0)) {
            data->event = fieldstg_event_start(0x4FC);
        }
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag385_start(void *arg0) {
    WstagObject *obj = object_new(wstag385_update, sizeof(WstagObject), 4);

    obj->manager = arg0;
    wstag385_funcs.setup();
    return obj;
}

void wstag385_event_1275_end(void) {
    gamestate_flags.set_flag(0x402D, 1);
    gamestate_flags.set_flag(0x7400, 1);
}

void wstag385_event_1276_end(void) {
    gamestate_flags.set_flag(0x402E, 1);
    gamestate_flags.set_flag(0x8168, 1);
}

