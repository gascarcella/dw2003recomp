void wstag295_update(WstagObject *obj, WstagEventData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        obj->base.next_state(obj);
        if (gamestate_data.progress == 0x21) {
            if (gamestate_flags.get_flag(0x1C39, 0) && gamestate_flags.get_flag(0x4057, 1) && gamestate_flags.get_flag(0x4058, 0)) {
                data->event = fieldstg_event_start(0x37B);
            } else if (gamestate_flags.get_flag(0x1C39, 0) && gamestate_flags.get_flag(0x4058, 1)) {
                data->event = fieldstg_event_start(0x37C);
            }
        }
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag295_start(void *arg0) {
    WstagObject *obj = object_new(wstag295_update, sizeof(WstagObject), sizeof(FieldstgEvent *));

    obj->manager = arg0;
    wstag295_funcs.setup();
    return obj;
}

