void wstag675_update();

void wstag675_update(WstagObject *obj, WstagEventData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        if (gamestate_data.progress == 0xF && gamestate_flags.get_flag(0x401E, 1)) {
            data->event = fieldstg_event_start(0x19B);
        }
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag675_start(void *arg0) {
    WstagObject *obj = object_new(wstag675_update, sizeof(WstagObject), 4);

    obj->manager = arg0;
    wstag675_funcs.setup();
    return obj;
}

void wstag675_event_390_end(void) {
    gamestate_flags.set_flag(0x4017, 1);
}

void wstag675_event_400_end(void) {
    gamestate_flags.set_flag(0x401A, 1);
}

void wstag675_event_410_end(void) {
    gamestate_flags.set_flag(0x401E, 1);
    gamestate_flags.set_flag(0x1C26, 1);
    gamestate_flags.set_flag(0x7400, 1);
}

void wstag675_setup(void) {
    fieldstg_stage.background_file = 0x4AF;
    fieldstg_stage.sprite_file = 0x04B00000;
    fieldstg_stage.sprites = wstag675_sprites;
    fieldstg_stage.map_events = wstag675_map_events;
    fieldstg_stage.mask_file = 0x4AE;
    fieldstg_stage.talk_file = records_language + 0xCC;
    fieldstg_stage.start_pos = (GamestatePos){ 0x17000, 0x1E000 };
    fieldstg_stage.start_dir = 0;
    fieldstg_stage.vram_places = wstag675_vram_places;
    fieldstg_stage.music = 0x3D;
    fieldstg_stage.sound = 0x60F40000;
    fieldstg_stage.actors = wstag675_actors;
    fieldstg_stage.events = wstag675_events;
    fieldstg_stage.battle_lists = &wstag675_battle_lists;
    fieldstg_attr.set_file(0, 0x04B00001);
    fieldstg_attr.set_file(7, 0x04B00002);
    fieldstg_attr.init_layer(0);
    if (gamestate_data.progress >= 0x27 && gamestate_data.progress < 0x29) {
        fieldstg_stage.music = 0x1F;
        fieldstg_stage.sound = 0x607C0000;
    }
    if (gamestate_data.progress >= 0xF && gamestate_data.progress < 0x18) {
        fieldstg_stage.music = 0x1F;
        fieldstg_stage.sound = 0x607C0000;
    }
}

