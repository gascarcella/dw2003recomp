    fieldstg_stage.start_pos = (GamestatePos){ 0x20000, 0xB900 };
    fieldstg_stage.start_dir = 0;
    fieldstg_stage.vram_places = wstag970_vram_places;
    fieldstg_stage.music = 0x1E;
    fieldstg_stage.sound = 0x60780000;
