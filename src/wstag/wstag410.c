void wstag410_update(WstagObject *obj) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag410_start(void *arg0) {
    WstagObject *obj = object_new(wstag410_update, sizeof(WstagObject), 0);

    obj->manager = arg0;
    wstag410_funcs.setup();
    return obj;
}

void wstag410_event_90_end(void) {
    gamestate_data.progress = 0x6;
}

void wstag410_setup(void) {
    fieldstg_stage.background_file = 0x39C;
    fieldstg_stage.sprite_file = 0x039D0000;
    fieldstg_stage.sprites = wstag410_sprites;
    fieldstg_stage.map_events = wstag410_map_events;
    fieldstg_stage.mask_file = 0x39B;
    fieldstg_stage.talk_file = records_language + 0xEF;
    fieldstg_stage.start_pos = (GamestatePos){ 0x26F00, 0xA800 };
    fieldstg_stage.start_dir = 0;
    fieldstg_stage.vram_places = wstag410_vram_places;
    fieldstg_stage.music = 0xE;
    fieldstg_stage.sound = 0x60380000;
    fieldstg_stage.actors = wstag410_actors;
    fieldstg_stage.color = wstag410_color;
    fieldstg_stage.events = wstag410_events;
    fieldstg_stage.battle_lists = &wstag410_battle_lists;
    fieldstg_attr.set_file(0, 0x039D0001);
    fieldstg_attr.set_file(7, 0x039D0002);
    fieldstg_attr.init_layer(0);
    if (gamestate_data.progress >= 0x27 && gamestate_data.progress < 0x29) {
        fieldstg_stage.music = 0x1F;
        fieldstg_stage.sound = 0x607C0000;
    }
}

