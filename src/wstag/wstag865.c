    fieldstg_stage.talk_file = records_language + 0xE1;
    fieldstg_stage.start_pos = (GamestatePos){ 0xF900, 0x14000 };
    fieldstg_stage.start_dir = 0;
    fieldstg_stage.vram_places = wstag865_vram_places;
    fieldstg_stage.music = 0x1E;
    fieldstg_stage.sound = 0x60780000;
    fieldstg_stage.actors = wstag865_actors;
