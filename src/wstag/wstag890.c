extern WstagExits *wstag890_exits[];
extern WstagFuncs wstag890_funcs;
extern FieldstgBattleLists wstag890_battle_lists[];
extern FieldstgVramPlace wstag890_vram_places[];
extern FieldstgPlacedActor *wstag890_actors[];
extern FieldstgSprite wstag890_sprites[];
extern FieldstgMapEvent wstag890_map_events[];

s32 wstag890_set_exits(FieldstgMapEvent *dst, WstagExits **list, s32 arg2, s32 arg3) {
    WstagExits *exits = *list;
    WstagExit *exit;

    if (exits == NULL) {
        return;
    }
    if (exits->route != arg2 || exits->room != arg3) {
        return wstag890_set_exits(dst, list + 1, arg2, arg3);
    }
    exit = exits->exits;
    dst->param = exit->stage;
    dst->x = exit->x;
    dst->y = exit->y;
    dst->dir = exit->dir;
    dst->route = exit->route;
    dst->room = exit->room;
    while (exit->next != NULL) {
        exit = exit->next;
        dst++;
        dst->param = exit->stage;
        dst->x = exit->x;
        dst->y = exit->y;
        dst->dir = exit->dir;
        dst->route = exit->route;
        dst->room = exit->room;
    }
}

void wstag890_update(WstagObject *obj) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        wstag890_set_exits(fieldstg_stage.map_events, wstag890_exits, gamestate_data.route,
                               gamestate_data.room);
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag890_start(void *arg0) {
    WstagObject *obj = object_new(wstag890_update, sizeof(WstagObject), 0);

    obj->manager = arg0;
    wstag890_funcs.setup();
    return obj;
}

void wstag890_setup(void) {
    fieldstg_stage.background_file = 0x695;
    fieldstg_stage.sprite_file = 0x06960000;
    fieldstg_stage.sprites = wstag890_sprites;
    fieldstg_stage.map_events = wstag890_map_events;
    fieldstg_stage.mask_file = 0x694;
    fieldstg_stage.talk_file = records_language + 0xE1;
    fieldstg_stage.start_pos = (GamestatePos){ 0x18200, 0x7E00 };
    fieldstg_stage.start_dir = 0;
    fieldstg_stage.vram_places = wstag890_vram_places;
    fieldstg_stage.music = 0x1E;
    fieldstg_stage.sound = 0x60780000;
    fieldstg_stage.actors = wstag890_actors;
    fieldstg_stage.battle_lists = fieldstg_stage.find_battle_lists(wstag890_battle_lists, gamestate_data.route);
    fieldstg_attr.set_file(0, 0x06960001);
    fieldstg_attr.set_file(7, 0x06960002);
    fieldstg_attr.set_file(4, 0x06960003);
    fieldstg_attr.init_layer(0);
}

