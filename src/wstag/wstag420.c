void wstag420_update();

void wstag420_update(WstagObject *obj, WstagEventData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        if (gamestate_data.progress == 4 && gamestate_flags.get_flag(0x4012, 1)) {
            data->event = fieldstg_event_start(0x47);
        }
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag420_start(void *arg0) {
    WstagObject *obj = object_new(wstag420_update, sizeof(WstagObject), 4);

    obj->manager = arg0;
    wstag420_funcs.setup();
    return obj;
}

void wstag420_event_70_end(void) {
    gamestate_flags.set_flag(0x4012, 1);
    gamestate_flags.set_flag(0x7401, 1);
}

void wstag420_event_71_end(void) {
    gamestate_flags.set_flag(0x8028, 1);
    gamestate_flags.set_flag(0x8009, 1);
    gamestate_data.progress = 5;
}

void wstag420_setup(void) {
    fieldstg_stage.background_file = 0x783;
    fieldstg_stage.sprite_file = 0x07840000;
    fieldstg_stage.sprites = wstag420_sprites;
    fieldstg_stage.map_events = wstag420_map_events;
    fieldstg_stage.mask_file = 0x782;
    fieldstg_stage.talk_file = records_language + 0xCC;
    fieldstg_stage.start_pos = (GamestatePos){ 0x1D100, 0x1F600 };
    fieldstg_stage.start_dir = 0;
    fieldstg_stage.vram_places = wstag420_vram_places;
    fieldstg_stage.music = 0xC;
    fieldstg_stage.sound = 0x60300000;
    fieldstg_stage.actors = wstag420_actors;
    fieldstg_stage.events = wstag420_events;
    fieldstg_stage.battle_lists = &wstag420_battle_lists;
    fieldstg_attr.set_file(0, 0x07840001);
    fieldstg_attr.set_file(7, 0x07840002);
    fieldstg_attr.init_layer(0);
    if (gamestate_data.progress >= 0x27 && gamestate_data.progress < 0x29) {
        fieldstg_stage.music = 0x1F;
        fieldstg_stage.sound = 0x607C0000;
    }
}

