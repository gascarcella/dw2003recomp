void wstag386_update(WstagObject *obj) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag386_start(void *arg0) {
    WstagObject *obj = object_new(wstag386_update, sizeof(WstagObject), 0);

    obj->manager = arg0;
    wstag386_funcs.setup();
    return obj;
}

