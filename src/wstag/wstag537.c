void wstag537_update(WstagObject *obj, WstagEventData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        if (gamestate_flags.get_flag(0x40CB, 1) && gamestate_flags.get_flag(0x40CC, 0)) {
            data->event = fieldstg_event_start(0x5B0);
        }
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag537_start(void *arg0) {
    WstagObject *obj = object_new(wstag537_update, sizeof(WstagObject), 4);

    obj->manager = arg0;
    wstag537_funcs.setup();
    return obj;
}

