extern FieldstgMapEvent wstag500_map_events[];
extern FieldstgEventDef wstag500_events[];

void wstag500_update(WstagObject *obj) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        obj->base.next_state(obj);
        break;
    case OBJECT_STATE_RUN:
    case OBJECT_STATE_DONE:
    case OBJECT_STATE_END:
        break;
    }
}

WstagObject *wstag500_start(void *arg0) {
    WstagObject *obj = object_new(wstag500_update, sizeof(WstagObject), sizeof(Object *));

    obj->manager = arg0;
    wstag500_funcs.setup();
    return obj;
}

void wstag500_event_250_end(void) {
    gamestate_flags.set_flag(0x400A, 1);
    gamestate_flags.set_flag(0x1A32, 1);
}

void wstag500_setup(void) {
    fieldstg_stage.background_file = 0x40D;
    fieldstg_stage.sprite_file = 0x040E0000;
    fieldstg_stage.sprites = wstag500_sprites;
    fieldstg_stage.map_events = wstag500_map_events;
    fieldstg_stage.mask_file = 0x40C;
    fieldstg_stage.talk_file = records_language + 0xCC;
    fieldstg_stage.start_pos = (GamestatePos){ 0x11100, 0x35300 };
    fieldstg_stage.start_dir = 0;
    fieldstg_stage.vram_places = wstag500_vram_places;
    fieldstg_stage.music = 0x12;
    fieldstg_stage.sound = 0x60480000;
    fieldstg_stage.actors = wstag500_actors;
    fieldstg_stage.events = wstag500_events;
    fieldstg_stage.battle_lists = &wstag500_battle_lists;
    fieldstg_attr.set_file(0, 0x040E0001);
    fieldstg_attr.set_file(7, 0x040E0002);
    fieldstg_attr.init_layer(0);
    if (gamestate_data.progress >= 0x27 && gamestate_data.progress < 0x29) {
        fieldstg_stage.music = 0x1F;
        fieldstg_stage.sound = 0x607C0000;
    }
}

