/* The overlay's main object: loads the files, lets the player choose a party member, runs the name entry
 * for it, and leaves with a fade. */

void stdgname_main_run(StdgnameMain *obj, StdgnameMainData *data) {
    s32 i;

    switch (obj->base.step) {
    case 0:
    default:
        if (data->party == NULL) {
            data->party = stdgname_party_create(obj);
        }
        obj->base.step++;
        break;
    case 1:
        if (data->party == NULL) {
            if (obj->member == -1) {
                obj->base.step = 5;
                break;
            }
            obj->base.step++;
        }
        break;
    case 2:
        if (data->name_entry == NULL) {
            i = gamestate_data.funcs.get_party_member(stdgname_funcs.member);
            data->name_entry = stdgname_entry_create(gamestate_data.funcs.get_record(i), i);
        }
        obj->base.step++;
        break;
    case 3:
        if (data->name_entry->base.step == 100) {
            data->name_entry->get_name(data->name_entry, (u8 *)gamestate_data.funcs.get_record(
                                                   gamestate_data.funcs.get_party_member(stdgname_funcs.member)));
            data->name_entry->close(data->name_entry);
            obj->base.step++;
        }
        break;
    case 4:
        if (data->name_entry->base.state == OBJECT_STATE_DONE) {
            data->name_entry->base.state = OBJECT_STATE_END;
            obj->base.set_step(obj, 0);
        }
        break;
    case 5:
        if (data->fade->base.state == OBJECT_STATE_DONE) {
            obj->base.set_state(obj, OBJECT_STATE_END);
        }
        break;
    }
}

/* Draws the scrolling background. */
void stdgname_main_draw_background(StdgnameMain *obj) {
    Sprite spr;

    sprite_init(&spr);
    spr.set_layer_id(obj->layer_id, 7);
    spr.set_vram_pos(0x280, 0);
    spr.draw(cdload_module.get_subfile_by_id(0x02880000), 0x31, 0, 0);
    if (obj->odd_frame != 0) {
        obj->scroll = obj->scroll++ < 0x5F ? obj->scroll : 0;
        obj->odd_frame = 0;
    } else {
        obj->odd_frame = 1;
    }
    spr.draw(cdload_module.get_subfile_by_id(0x02880000), 0x24, obj->scroll, obj->scroll);
}

void stdgname_main_update(StdgnameMain *obj, StdgnameMainData *data) {
    switch (obj->base.state) {
    case OBJECT_STATE_INIT:
    default:
        switch (obj->base.step) {
        case 0:
        default:
            stdgname_funcs.load();
            obj->base.step++;
            break;
        case 1:
            if (stdgname_funcs.is_loading() == 0) {
                obj->base.next_state(obj);
            }
            break;
        }
        break;
    case OBJECT_STATE_RUN:
        stdgname_main_run(obj, data);
        stdgname_main_draw_background(obj);
        break;
    case OBJECT_STATE_DONE:
        if (data->unk_0C == NULL) {
            obj->base.set_state(obj, OBJECT_STATE_RUN);
        }
        stdgname_main_draw_background(obj);
        break;
    case OBJECT_STATE_END:
        gamestate_data.funcs.set_next_map(gamestate_data.field_map, 0);
        break;
    }
}

/* Fades out (StdgnameMain.fade_out). */
void stdgname_main_fade_out(StdgnameMain *obj) {
    StdgnameMainData *data = (StdgnameMainData *)obj->base.children;

    data->fade = stdgname_fade_create();
    data->fade->start(data->fade, 0, 30);
}

StdgnameMain *stdgname_main_create(void) {
    StdgnameMain *obj = object_new(stdgname_main_update, sizeof(StdgnameMain), sizeof(StdgnameMainData));

    obj->fade_out = stdgname_main_fade_out;
    obj->layer_id = 0x1000;
    return obj;
}

/* Starts loading the overlay's files (stdgname_funcs.load). */
void stdgname_load_files(void) {
    Tim tim;

    heap_funcs.bzero(&stdgname_funcs.member, sizeof(stdgname_funcs.member));
    tim_init(&tim);
    tim.set_image_pos(0x280, 0);
    tim.load_all(cdload_module.get_subfile_by_id(0x02890000));
    cdload_module.queue_file(records_language + 0x40);
    cdload_module.queue_file(0x771);
    cdload_module.queue_file(records_language + 0x86);
}

/* Returns non-zero while one of the overlay's files is still loading (stdgname_funcs.is_loading). */
s32 stdgname_is_loading(void) {
    if (!cdload_module.is_loading(0x771) && !cdload_module.is_loading(records_language + 0x40)) {
        return cdload_module.is_loading(records_language + 0x86) != 0;
    }
    return 1;
}

/* window_anim_start (include/window_anim.h), byte for byte. */
void stdgname_anim_start(WindowAnim *anim, s32 open) {
    anim->running = 1;
    if (open) {
        sound_module.play(0x40019);
        anim->step = 0x1000 / anim->duration;
        anim->level = 0;
    } else {
        sound_module.play(0x4001A);
        anim->level = 0x1000;
        anim->step = -(0x1000 / anim->duration * 2);
    }
}

/* window_anim_update (include/window_anim.h), byte for byte. */
s32 stdgname_anim_update(WindowAnim *anim) {
    if (anim->running == 0) {
        return 1;
    }
    anim->level += anim->step;
    if (anim->step > 0) {
        if (anim->level > 0x1000) {
            anim->level = 0x1000;
            anim->running = 0;
            return 1;
        }
    } else if (anim->level < 0) {
        anim->level = 0;
        anim->running = 0;
        return 1;
    }
    return 0;
}

